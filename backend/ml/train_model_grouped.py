"""
Train and compare URL-only models using a domain-grouped holdout.

Uses dataset.csv generated by prepare_public_dataset.py.
The test split is held out by registrable domain, so URLs from a domain cannot
appear in both training and test sets. Test metrics are reported once after
selecting a model/threshold on training/validation data.
"""

from __future__ import annotations

import json
import os
import warnings

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import (
    RandomForestClassifier,
    ExtraTreesClassifier,
    HistGradientBoostingClassifier,
)
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
    classification_report,
    balanced_accuracy_score,
)
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler


BASE_DIR = os.path.dirname(os.path.abspath(__file__))

DATA_FILE = os.path.join(
    BASE_DIR,
    "data",
    "dataset.csv",
)

MODEL_FILE = os.path.join(
    BASE_DIR,
    "phishing_model.joblib",
)

THRESHOLD_FILE = os.path.join(
    BASE_DIR,
    "model_threshold.json",
)

REPORT_DIR = os.path.join(
    BASE_DIR,
    "reports",
)

REPORT_FILE = os.path.join(
    REPORT_DIR,
    "model_evaluation.json",
)

SEED = 42


FEATURE_COLUMNS = [
    "url_length",
    "hostname_length",
    "is_https",
    "dot_count",
    "hyphen_count",
    "has_at_symbol",
    "is_ip",
    "digit_count",
    "keyword_count",
    "path_length",
    "num_slashes",
]


def class_counts(y):
    return {
        str(int(k)): int(v)
        for k, v in pd.Series(y)
        .value_counts()
        .sort_index()
        .items()
    }


def safe_split(df, n_splits=5, fold=0):
    splitter = StratifiedGroupKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=SEED,
    )

    splits = list(
        splitter.split(
            df[FEATURE_COLUMNS],
            df["label"],
            groups=df["domain_group"],
        )
    )

    return splits[fold]


def evaluate(model, X, y, threshold=0.5):
    classes = list(model.classes_)

    if 1 not in classes:
        raise ValueError(
            "Model does not have phishing class 1."
        )

    prob = model.predict_proba(X)[
        :,
        classes.index(1),
    ]

    pred = (prob >= threshold).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y,
        pred,
        labels=[0, 1],
    ).ravel()

    try:
        auc = float(
            roc_auc_score(
                y,
                prob,
            )
        )
    except ValueError:
        auc = None

    return {
        "threshold": float(threshold),
        "accuracy": float(
            accuracy_score(
                y,
                pred,
            )
        ),
        "balanced_accuracy": float(
            balanced_accuracy_score(
                y,
                pred,
            )
        ),
        "precision_phishing": float(
            precision_score(
                y,
                pred,
                zero_division=0,
            )
        ),
        "recall_phishing": float(
            recall_score(
                y,
                pred,
                zero_division=0,
            )
        ),
        "f1_phishing": float(
            f1_score(
                y,
                pred,
                zero_division=0,
            )
        ),
        "roc_auc": auc,
        "confusion_matrix_labels_order": [
            "legitimate_0",
            "phishing_1",
        ],
        "confusion_matrix": [
            [
                int(tn),
                int(fp),
            ],
            [
                int(fn),
                int(tp),
            ],
        ],
        "false_positives": int(fp),
        "false_negatives": int(fn),
        "support": int(len(y)),
        "class_counts": class_counts(y),
    }, prob


def main():

    # ---------------------------------------------------------
    # 1. Check dataset
    # ---------------------------------------------------------

    if not os.path.isfile(DATA_FILE):
        raise FileNotFoundError(
            f"{DATA_FILE} not found. "
            "Run: python backend/ml/prepare_public_dataset.py"
        )

    df = pd.read_csv(DATA_FILE)

    required = set(
        FEATURE_COLUMNS
        + [
            "label",
            "domain_group",
        ]
    )

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            f"Dataset missing required columns: {sorted(missing)}"
        )

    df = df.dropna(
        subset=FEATURE_COLUMNS
        + [
            "label",
            "domain_group",
        ]
    ).copy()

    df["label"] = df["label"].astype(int)

    df = df[
        df["label"].isin([0, 1])
    ].reset_index(drop=True)

    if df["label"].nunique() != 2:
        raise ValueError(
            "Need both classes: "
            "label 0 legitimate, label 1 phishing."
        )

    if df["domain_group"].nunique() < 5:
        raise ValueError(
            "Need at least five distinct domain groups "
            "for grouped evaluation."
        )

    os.makedirs(
        REPORT_DIR,
        exist_ok=True,
    )

    # ---------------------------------------------------------
    # 2. Load existing model for baseline comparison
    # ---------------------------------------------------------

    existing_model = None

    if os.path.isfile(MODEL_FILE):

        try:
            existing_model = joblib.load(
                MODEL_FILE
            )

            print(
                "Existing model loaded for baseline comparison."
            )

        except Exception as exc:

            warnings.warn(
                "Could not load existing model "
                f"for baseline comparison: {exc}"
            )

    # ---------------------------------------------------------
    # 3. Domain-grouped test split
    # ---------------------------------------------------------

    dev_idx, test_idx = safe_split(
        df,
        n_splits=5,
        fold=0,
    )

    dev = df.iloc[
        dev_idx
    ].reset_index(drop=True)

    test = df.iloc[
        test_idx
    ].reset_index(drop=True)

    # ---------------------------------------------------------
    # 4. Domain-grouped train/validation split
    # ---------------------------------------------------------

    train_idx, val_idx = safe_split(
        dev,
        n_splits=4,
        fold=0,
    )

    train_df = dev.iloc[
        train_idx
    ].reset_index(drop=True)

    val_df = dev.iloc[
        val_idx
    ].reset_index(drop=True)

    train_groups = set(
        train_df["domain_group"]
    )

    val_groups = set(
        val_df["domain_group"]
    )

    test_groups = set(
        test["domain_group"]
    )

    assert not (
        train_groups & val_groups
    ), "Domain leakage between train and validation."

    assert not (
        train_groups & test_groups
    ), "Domain leakage between train and test."

    assert not (
        val_groups & test_groups
    ), "Domain leakage between validation and test."

    # ---------------------------------------------------------
    # 5. Prepare features
    # ---------------------------------------------------------

    X_train = train_df[
        FEATURE_COLUMNS
    ]

    y_train = train_df[
        "label"
    ]

    X_val = val_df[
        FEATURE_COLUMNS
    ]

    y_val = val_df[
        "label"
    ]

    X_test = test[
        FEATURE_COLUMNS
    ]

    y_test = test[
        "label"
    ]

    # ---------------------------------------------------------
    # 6. Candidate models
    # ---------------------------------------------------------

    candidates = {

        "random_forest": RandomForestClassifier(
            n_estimators=300,
            class_weight="balanced_subsample",
            min_samples_leaf=2,
            random_state=SEED,
            n_jobs=-1,
        ),

        "extra_trees": ExtraTreesClassifier(
            n_estimators=300,
            class_weight="balanced",
            min_samples_leaf=2,
            random_state=SEED,
            n_jobs=-1,
        ),

        "logistic_regression": Pipeline(
            [
                (
                    "scale",
                    StandardScaler(),
                ),
                (
                    "model",
                    LogisticRegression(
                        max_iter=2000,
                        class_weight="balanced",
                        random_state=SEED,
                    ),
                ),
            ]
        ),
    }

    results = {}
    fitted = {}

    print(
        "Rows:",
        len(df),
        "| classes (0=legitimate, 1=phishing):",
        class_counts(df["label"]),
    )

    print(
        "Split sizes:",
        {
            "train": len(train_df),
            "validation": len(val_df),
            "test": len(test),
        },
    )

    print(
        "Domain groups:",
        {
            "train": len(train_groups),
            "validation": len(val_groups),
            "test": len(test_groups),
        },
    )

    print(
        "\nTraining candidate models "
        "(phishing class is label 1)..."
    )

    # ---------------------------------------------------------
    # 7. Train candidate models
    # ---------------------------------------------------------

    for name, model in candidates.items():

        print(
            f"  Fitting {name}..."
        )

        model.fit(
            X_train,
            y_train,
        )

        # Choose threshold using validation only.
        # F2 weights recall more heavily than precision.

        if hasattr(model, "classes_"):
            classes = list(
                model.classes_
            )
        else:
            classes = list(
                model.named_steps[
                    "model"
                ].classes_
            )

        val_prob = model.predict_proba(
            X_val
        )[
            :,
            classes.index(1),
        ]

        best = None

        for threshold in np.arange(
            0.20,
            0.801,
            0.02,
        ):

            pred = (
                val_prob >= threshold
            ).astype(int)

            precision = precision_score(
                y_val,
                pred,
                zero_division=0,
            )

            recall = recall_score(
                y_val,
                pred,
                zero_division=0,
            )

            beta = 2.0

            denom = (
                beta * beta * precision
                + recall
            )

            f2 = (
                (1 + beta * beta)
                * precision
                * recall
                / denom
                if denom
                else 0.0
            )

            # Penalize thresholds that flag
            # almost everything.

            positive_rate = float(
                pred.mean()
            )

            penalty = max(
                0.0,
                positive_rate - 0.80,
            ) * 0.25

            score = (
                f2 - penalty
            )

            if (
                best is None
                or score
                > best["selection_score"]
            ):

                best = {
                    "threshold": float(
                        threshold
                    ),
                    "selection_score": float(
                        score
                    ),
                    "validation_f2": float(
                        f2
                    ),
                    "validation_precision": float(
                        precision
                    ),
                    "validation_recall": float(
                        recall
                    ),
                    "validation_positive_rate": positive_rate,
                }

        results[name] = {
            "validation_threshold_selection": best
        }

        fitted[name] = model

        print(
            f"    selected threshold="
            f"{best['threshold']:.2f}; "
            f"validation precision="
            f"{best['validation_precision']:.3f}; "
            f"recall="
            f"{best['validation_recall']:.3f}"
        )

    # ---------------------------------------------------------
    # 8. Select best model using validation only
    # ---------------------------------------------------------

    selected_name = max(
        results,
        key=lambda n:
        results[n][
            "validation_threshold_selection"
        ]["selection_score"],
    )

    selected_model = fitted[
        selected_name
    ]

    threshold = results[
        selected_name
    ][
        "validation_threshold_selection"
    ][
        "threshold"
    ]

    print(
        f"\nSelected on validation only: "
        f"{selected_name}; "
        f"threshold={threshold:.2f}"
    )

    # ---------------------------------------------------------
    # 9. Evaluate all models on untouched test set
    # ---------------------------------------------------------

    for name, model in fitted.items():

        threshold_n = results[
            name
        ][
            "validation_threshold_selection"
        ][
            "threshold"
        ]

        metrics, _ = evaluate(
            model,
            X_test,
            y_test,
            threshold_n,
        )

        results[name][
            "test_metrics"
        ] = metrics

        print(
            f"\n{name} TEST:"
        )

        print(
            json.dumps(
                metrics,
                indent=2,
            )
        )

    # ---------------------------------------------------------
    # 10. Baseline comparison
    # ---------------------------------------------------------

    selected_metrics = results[
        selected_name
    ][
        "test_metrics"
    ]

    baseline_metrics = None

    if existing_model is not None:

        try:

            baseline_metrics, _ = evaluate(
                existing_model,
                X_test,
                y_test,
                threshold=0.40,
            )

            print(
                "\nexisting_model_baseline TEST "
                "(threshold=0.40):"
            )

            print(
                json.dumps(
                    baseline_metrics,
                    indent=2,
                )
            )

        except Exception as exc:

            warnings.warn(
                "Existing model could not be "
                "evaluated on this dataset's "
                f"feature schema: {exc}"
            )

    # ---------------------------------------------------------
    # 11. Build evaluation report
    # ---------------------------------------------------------

    report = {

        "dataset_file":
            "backend/ml/data/dataset.csv",

        "label_mapping": {
            "0": "legitimate",
            "1": "phishing",
        },

        "feature_columns":
            FEATURE_COLUMNS,

        "split_method":
            "StratifiedGroupKFold by registrable "
            "domain; test set held out before "
            "model/threshold selection",

        "seed":
            SEED,

        "row_counts": {
            "all": len(df),
            "train": len(train_df),
            "validation": len(val_df),
            "test": len(test),
        },

        "class_counts": {
            "all":
                class_counts(
                    df["label"]
                ),

            "train":
                class_counts(
                    y_train
                ),

            "validation":
                class_counts(
                    y_val
                ),

            "test":
                class_counts(
                    y_test
                ),
        },

        "domain_group_counts": {
            "train":
                len(train_groups),

            "validation":
                len(val_groups),

            "test":
                len(test_groups),
        },

        "domain_overlap_checks": {
            "train_validation":
                len(
                    train_groups
                    & val_groups
                ),

            "train_test":
                len(
                    train_groups
                    & test_groups
                ),

            "validation_test":
                len(
                    val_groups
                    & test_groups
                ),
        },

        "selected_model":
            selected_name,

        "selected_threshold":
            threshold,

        "selected_model_test_metrics":
            selected_metrics,

        "existing_model_baseline_test_metrics_threshold_0_40":
            baseline_metrics,

        "all_models":
            results,

        "important_limitations": [
            "A domain-grouped test is more conservative "
            "than a random URL split, but does not prove "
            "performance on all future phishing campaigns.",

            "Dataset labels and collection time can be "
            "noisy or stale.",

            "The risk score emitted by the application "
            "should not be described as a calibrated "
            "probability unless calibrated separately.",

            "Threshold was selected using validation "
            "data only; final test data was not used "
            "to select the model or threshold.",
        ],
    }

    # ---------------------------------------------------------
    # 12. Save evaluation report
    # ---------------------------------------------------------

    with open(
        REPORT_FILE,
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            report,
            f,
            indent=2,
        )

    # ---------------------------------------------------------
    # 13. Save threshold configuration
    # ---------------------------------------------------------

    threshold_config = {

        "model":
            selected_name,

        "threshold":
            threshold,

        "label_mapping": {
            "0": "legitimate",
            "1": "phishing",
        },

        "feature_columns":
            FEATURE_COLUMNS,
    }

    with open(
        THRESHOLD_FILE,
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            threshold_config,
            f,
            indent=2,
        )

    # ---------------------------------------------------------
    # 14. Save selected model
    # ---------------------------------------------------------

    joblib.dump(
        selected_model,
        MODEL_FILE,
    )

    print(
        f"\nSaved model: {MODEL_FILE}"
    )

    print(
        f"Saved threshold config: "
        f"{THRESHOLD_FILE}"
    )

    print(
        f"Saved evaluation report: "
        f"{REPORT_FILE}"
    )

    # ---------------------------------------------------------
    # 15. Final metrics
    # ---------------------------------------------------------

    print(
        "\nSelected model FINAL TEST METRICS:"
    )

    print(
        json.dumps(
            selected_metrics,
            indent=2,
        )
    )

    print(
        "\nIMPORTANT: these metrics apply to "
        "the domain-held-out test split from "
        "this dataset, not to all real-world URLs."
    )


if __name__ == "__main__":
    main()