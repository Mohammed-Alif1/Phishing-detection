"""
Build a URL-feature dataset from source CSVs.

Expected inputs under backend/ml/data/:
  verified_online.csv : PhishTank CSV export with a `url` column.
  top-1m.csv          : Tranco CSV with rank,domain columns (no header).

Important: Tranco popularity is a proxy for legitimate examples, not a guarantee
that every domain is benign. The resulting model should be described accordingly.
No synthetic URLs are generated by this script.
"""
import ipaddress
import os
import re
from urllib.parse import urlparse, unquote

import pandas as pd

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, "data")
PHISHTANK_FILE = os.path.join(DATA_DIR, "verified_online.csv")
TRANCO_FILE = os.path.join(DATA_DIR, "top-1m.csv")
OUTPUT_FILE = os.path.join(DATA_DIR, "dataset.csv")
NUM_LEGIT_SAMPLES = 20000
RANDOM_SEED = 42

SUSPICIOUS_KEYWORDS = [
    "login", "verify", "secure", "update", "account", "bank", "confirm",
    "password", "signin", "webscr", "paypal", "ebay", "amazon", "apple",
    "microsoft", "payment", "wallet", "authentication", "recover", "billing",
    "unlock", "validate", "support", "reset",
]

FEATURE_COLUMNS = [
    "url_length", "hostname_length", "is_https", "dot_count", "hyphen_count",
    "has_at_symbol", "is_ip", "digit_count", "keyword_count", "path_length",
    "num_slashes",
]


def is_ip_address(hostname):
    try:
        ipaddress.ip_address(hostname)
        return True
    except ValueError:
        return False


def extract_features(url):
    parsed = urlparse(url)
    hostname = (parsed.hostname or "").lower().rstrip(".")
    full_url = unquote(url).lower()
    return {
        "url_length": len(url),
        "hostname_length": len(hostname),
        "is_https": int(parsed.scheme.lower() == "https"),
        "dot_count": hostname.count("."),
        "hyphen_count": hostname.count("-"),
        "has_at_symbol": int("@" in url),
        "is_ip": int(is_ip_address(hostname)),
        "digit_count": sum(ch.isdigit() for ch in url),
        "keyword_count": sum(1 for word in SUSPICIOUS_KEYWORDS if word in full_url),
        "path_length": len(parsed.path or ""),
        "num_slashes": url.count("/"),
    }


def valid_http_url(value):
    if not isinstance(value, str):
        return False
    value = value.strip()
    if not value or len(value) > 4096:
        return False
    try:
        parsed = urlparse(value)
        return parsed.scheme.lower() in {"http", "https"} and bool(parsed.hostname)
    except ValueError:
        return False


MULTI_LABEL_SUFFIXES = {
    "co.uk", "org.uk", "ac.uk", "gov.uk", "com.au", "net.au", "org.au",
    "co.in", "firm.in", "net.in", "org.in", "gen.in", "com.br", "com.mx",
    "co.jp", "co.nz", "com.sg", "com.tr", "com.cn", "com.tw", "co.za",
}


def host_key(url):
    """Approximate registrable domain for grouping; handles common compound suffixes."""
    try:
        host = (urlparse(url).hostname or "").lower().rstrip(".")
        if host.startswith("www."):
            host = host[4:]
        labels = host.split(".")
        if len(labels) <= 2:
            return host
        suffix2 = ".".join(labels[-2:])
        if suffix2 in MULTI_LABEL_SUFFIXES and len(labels) >= 3:
            return ".".join(labels[-3:])
        return suffix2
    except ValueError:
        return ""


def build_dataset():
    os.makedirs(DATA_DIR, exist_ok=True)
    if not os.path.exists(PHISHTANK_FILE):
        raise FileNotFoundError(
            f"Missing {PHISHTANK_FILE}. Download the official PhishTank CSV and save it as verified_online.csv."
        )
    if not os.path.exists(TRANCO_FILE):
        raise FileNotFoundError(
            f"Missing {TRANCO_FILE}. Download a Tranco top-sites CSV and save it as top-1m.csv."
        )

    phish_df = pd.read_csv(PHISHTANK_FILE, low_memory=False)
    if "url" not in phish_df.columns:
        raise ValueError("PhishTank input must contain a 'url' column.")
    # Official verified_online feed already contains verified and online entries;
    # filter again when columns are available.
    for col in ("verified", "online"):
        if col in phish_df.columns:
            phish_df = phish_df[phish_df[col].astype(str).str.lower().eq("yes")]
    phish_urls = phish_df["url"].dropna().astype(str).str.strip().tolist()
    phish_urls = list(dict.fromkeys(u for u in phish_urls if valid_http_url(u)))

    tranco_df = pd.read_csv(TRANCO_FILE, header=None, names=["rank", "domain"], dtype=str)
    domains = tranco_df["domain"].dropna().astype(str).str.strip().str.lower()
    domains = domains[domains.str.contains(r"\.", regex=True)]
    domains = list(dict.fromkeys(d for d in domains if re.fullmatch(r"[a-z0-9.-]+", d)))
    domains = domains[:NUM_LEGIT_SAMPLES]

    phishing_hosts = {host_key(u) for u in phish_urls}
    legitimate_urls = [f"https://{d}/" for d in domains if d not in phishing_hosts]
    # Deduplicate phishing by URL; remove a domain overlap from the proxy-legitimate class.
    phishing_hosts = {host_key(u) for u in phish_urls}
    rows = []
    for url, label, source in (
        *((u, 1, "phishtank_verified_online") for u in phish_urls),
        *((u, 0, "tranco_popular_domain_proxy") for u in legitimate_urls),
    ):
        host = host_key(url)
        row = {"url": url, "domain": host, "label": label, "source": source}
        row.update(extract_features(url))
        rows.append(row)

    dataset = pd.DataFrame(rows).drop_duplicates(subset=["url"])
    dataset = dataset[dataset["domain"].astype(bool)]
    # Keep distinct URL paths, but group them by registrable-domain approximation during splitting.
    # Do not silently assign conflicting labels to the same hostname.
    conflicts = dataset.groupby("domain")["label"].nunique()
    conflict_domains = set(conflicts[conflicts > 1].index)
    if conflict_domains:
        dataset = dataset[~dataset["domain"].isin(conflict_domains)]

    dataset = dataset.sample(frac=1, random_state=RANDOM_SEED).reset_index(drop=True)
    dataset.to_csv(OUTPUT_FILE, index=False)
    print(f"Saved {len(dataset):,} unique domain-level samples to {OUTPUT_FILE}")
    print("Class counts (0=Tranco popular-domain proxy; 1=verified PhishTank):")
    print(dataset["label"].value_counts().sort_index().to_string())
    print(f"Unique domains: {dataset['domain'].nunique():,}")
    print("Note: popular-domain membership is not a verified benign label.")
    print("No synthetic phishing URLs were generated.")


if __name__ == "__main__":
    build_dataset()
